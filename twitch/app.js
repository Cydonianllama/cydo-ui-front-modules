function BuildChannelItem(data) {
  const item = document.createElement('div')
  item.classList.add('channel-item')
  item.innerHTML = `
  <div>
    <div class="channel-item--avatar">
      <img style="height:100%; width: 100%" src="${data.avatar}" />
    </div>
  </div>
  <div style="flex: 1; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; ">
    <div class="channel-item--title">${data.title}</div>
    <div class="channel-item--subtitle">${data.subtitle}</div>
  </div>
  <div style="display:flex; align-items: center; gap: .4rem;">
    ${data.status == 'ONLINE' ? `
      <div class = "channel-item--status active"></div>
      <div class="channel-item--counter">${data.counter}</div>
    ` : ''}

    ${data.status == 'OFFLINE' ? `
      <div class = "channel-item--offline">Offline</div>
    ` : ''}
  </div>
  `
  return item;
}

function BuildMessageItem(data) {
  const item = document.createElement('div')
  item.classList.add('chat-message')
  item.innerHTML = `
  <div style="display: inline">
    <div class = "chat-message--bagdes">${data.badges.map(el => `<div style ="height: 15px; width: 15px; border-radius: 5px; overflow: hidden;"><img style = "height: 100%; width: 100%;" src="${el.url}" /></div>`)}</div>
    <div style="color: ${data.color};" class = "chat-message--name">${data.name}:</div>
  </div>
  <div class = "chat-message--message">${data.message}</div>
  `
  return item;
}

