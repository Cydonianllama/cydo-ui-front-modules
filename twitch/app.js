function bootstrap() {

  // 
  // build followed channels
  //
  const followedContainer = document.getElementById('followed-container')
  if (followedContainer) {
    for (let item of followedChannels) {
      followedContainer.append(BuildChannelItem(item))
    }
  }


  // 
  // build live channels
  // 
  const liveChannelsContainerRef = document.getElementById('livechannels')
  if (liveChannelsContainerRef) {
    for (let item of liveChannels) {
      liveChannelsContainerRef.append(BuildChannelItem(item))
    }
  }

  //
  // messages
  //
  const messagesRef = document.getElementById('message-container')
  if (messagesRef) {
    for (let item of messages) {
      messagesRef.append(BuildMessageItem(item))
    }
  }

}

